-- Schema inicial do EMPREST.AI para PostgreSQL/Supabase.
-- Execute em uma única transação.

begin;

create extension if not exists pgcrypto;

create table if not exists usuarios (
    id uuid primary key default gen_random_uuid(),
    nome varchar(120) not null check (btrim(nome) <> ''),
    email varchar(254) not null check (btrim(email) <> ''),
    papel varchar(20) not null check (papel in ('COLABORADOR', 'OPERACOES')),
    ativo boolean not null default true,
    criado_em timestamptz not null default now(),
    atualizado_em timestamptz not null default now()
);

create unique index if not exists ux_usuarios_email_ci
    on usuarios (lower(email));

create table if not exists categorias (
    id smallint generated by default as identity primary key,
    nome varchar(60) not null check (btrim(nome) <> ''),
    ativa boolean not null default true
);

create unique index if not exists ux_categorias_nome_ci
    on categorias (lower(nome));

create table if not exists equipamentos (
    id uuid primary key default gen_random_uuid(),
    nome varchar(160) not null check (btrim(nome) <> ''),
    patrimonio varchar(60),
    categoria_id smallint not null references categorias(id),
    status_operacional varchar(20) not null default 'DISPONIVEL'
        check (status_operacional in ('DISPONIVEL', 'MANUTENCAO', 'INATIVO')),
    observacao text,
    criado_em timestamptz not null default now(),
    atualizado_em timestamptz not null default now()
);

create unique index if not exists ux_equipamentos_patrimonio
    on equipamentos (patrimonio)
    where patrimonio is not null;

create index if not exists ix_equipamentos_catalogo
    on equipamentos (categoria_id, status_operacional);

create table if not exists emprestimos (
    id uuid primary key default gen_random_uuid(),
    equipamento_id uuid not null references equipamentos(id),
    usuario_id uuid not null references usuarios(id),
    retirado_em timestamptz not null default now(),
    previsto_para date not null,
    devolvido_em timestamptz,
    devolucao_registrada_por_id uuid references usuarios(id),
    observacao_devolucao text,
    criado_em timestamptz not null default now(),
    constraint ck_emprestimos_prazo check (previsto_para >= retirado_em::date),
    constraint ck_emprestimos_devolucao_data check (
        devolvido_em is null or devolvido_em >= retirado_em
    ),
    constraint ck_emprestimos_devolucao_responsavel check (
        (devolvido_em is null and devolucao_registrada_por_id is null)
        or (devolvido_em is not null and devolucao_registrada_por_id is not null)
    )
);

create unique index if not exists ux_emprestimos_equipamento_ativo
    on emprestimos (equipamento_id)
    where devolvido_em is null;

create index if not exists ix_emprestimos_usuario_ativos
    on emprestimos (usuario_id, previsto_para)
    where devolvido_em is null;

create index if not exists ix_emprestimos_prazo_ativos
    on emprestimos (previsto_para)
    where devolvido_em is null;

create table if not exists historico_status_equipamento (
    id bigint generated by default as identity primary key,
    equipamento_id uuid not null references equipamentos(id),
    status_anterior varchar(20) check (
        status_anterior is null
        or status_anterior in ('DISPONIVEL', 'MANUTENCAO', 'INATIVO')
    ),
    status_novo varchar(20) not null check (
        status_novo in ('DISPONIVEL', 'MANUTENCAO', 'INATIVO')
    ),
    observacao text,
    alterado_por_id uuid not null references usuarios(id),
    alterado_em timestamptz not null default now()
);

create index if not exists ix_historico_status_equipamento
    on historico_status_equipamento (equipamento_id, alterado_em desc);

create or replace function definir_atualizado_em()
returns trigger
language plpgsql
as $$
begin
    new.atualizado_em := now();
    return new;
end;
$$;

drop trigger if exists tr_usuarios_atualizado_em on usuarios;
create trigger tr_usuarios_atualizado_em
before update on usuarios
for each row execute function definir_atualizado_em();

drop trigger if exists tr_equipamentos_atualizado_em on equipamentos;
create trigger tr_equipamentos_atualizado_em
before update on equipamentos
for each row execute function definir_atualizado_em();

create or replace function validar_novo_emprestimo()
returns trigger
language plpgsql
as $$
declare
    quantidade_ativa integer;
    equipamento_status varchar(20);
    usuario_ativo boolean;
begin
    if new.devolvido_em is not null then
        return new;
    end if;

    perform pg_advisory_xact_lock(hashtextextended(new.equipamento_id::text, 0));
    perform pg_advisory_xact_lock(hashtextextended(new.usuario_id::text, 0));

    select status_operacional into equipamento_status
    from equipamentos
    where id = new.equipamento_id
    for update;

    if not found then
        raise exception 'Equipamento inexistente.';
    end if;

    if equipamento_status <> 'DISPONIVEL' then
        raise exception 'Equipamento não está disponível para empréstimo.';
    end if;

    select ativo into usuario_ativo
    from usuarios
    where id = new.usuario_id;

    if not found or not usuario_ativo then
        raise exception 'Usuário não está ativo para empréstimo.';
    end if;

    select count(*) into quantidade_ativa
    from emprestimos
    where usuario_id = new.usuario_id
      and devolvido_em is null;

    if quantidade_ativa >= 3 then
        raise exception 'Usuário já possui o limite de 3 empréstimos ativos.';
    end if;

    return new;
end;
$$;

drop trigger if exists tr_validar_novo_emprestimo on emprestimos;
create trigger tr_validar_novo_emprestimo
before insert on emprestimos
for each row execute function validar_novo_emprestimo();

create or replace function impedir_status_com_emprestimo_ativo()
returns trigger
language plpgsql
as $$
begin
    if new.status_operacional <> old.status_operacional
       and new.status_operacional in ('MANUTENCAO', 'INATIVO')
       and exists (
           select 1
           from emprestimos
           where equipamento_id = old.id
             and devolvido_em is null
       ) then
        raise exception 'Não é possível alterar o status de equipamento com empréstimo ativo.';
    end if;

    return new;
end;
$$;

drop trigger if exists tr_impedir_status_com_emprestimo_ativo on equipamentos;
create trigger tr_impedir_status_com_emprestimo_ativo
before update of status_operacional on equipamentos
for each row execute function impedir_status_com_emprestimo_ativo();

insert into categorias (nome)
values ('Notebook'), ('Monitor'), ('Cabo'), ('Câmera'), ('Acessório')
on conflict (lower(nome)) do nothing;

commit;
